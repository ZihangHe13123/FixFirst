"""Write COMPARISON.md: every setting and effect, before and after, from before/ and after/ (no other input).

    python compare.py
"""
import json
from pathlib import Path

HERE = Path(__file__).resolve().parent
manifest = json.loads((HERE / "MANIFEST.json").read_text(encoding="utf-8"))
FIELDS = (("t_interval_excludes_zero", "t excludes 0"), ("t_interval_covers_truth", "t covers truth"),
          ("bootstrap_excludes_zero", "bootstrap excludes 0"), ("bootstrap_covers_truth", "bootstrap covers truth"),
          ("sign_test_p_below_0_05", "sign p < 0.05"))
lines = ["# Before and after, setting by setting", "",
         "Generated by `compare.py` from `before/` and `after/`. Shares of 2000 replicates. Before: decisions on "
         "intervals rounded to three decimals, and a replicate without an interval counted as the point estimate. "
         "After (7914699): decisions on unrounded intervals; a replicate whose task differences are all equal has no "
         "interval and neither excludes 0 nor covers the truth (`no interval`). The sign test did not change.", "",
         "| Setting | Effect parameter | True mean gain | " + " | ".join(f"{label} (before → after)" for _, label in FIELDS)
         + " | No interval (after) |", "|---" * (4 + len(FIELDS)) + "|"]
for key, setting in manifest["settings"].items():
    before = json.loads((HERE / "before" / f"{key}.json").read_text(encoding="utf-8"))["simulation"]
    after = json.loads((HERE / "after" / f"{key}.json").read_text(encoding="utf-8"))["simulation"]
    for old, new in zip(before, after):
        assert old["effect"] == new["effect"] and old["true_mean_difference"] == new["true_mean_difference"]
        cells = " | ".join(f"{old[field]:.3f} → {new[field]:.3f}" for field, _ in FIELDS)
        lines.append(f"| {key} | {new['effect']} | {new['true_mean_difference']} | {cells} | {new['no_interval']:.3f} |")
(HERE / "COMPARISON.md").write_text("\n".join(lines) + "\n", encoding="utf-8")
print(f"{len(lines) - 6} rows")
