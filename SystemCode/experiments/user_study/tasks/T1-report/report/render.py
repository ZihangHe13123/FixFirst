from jinja2 import Environment, Markup

TEMPLATE = (
    "<h1>{{ title }}</h1>"
    "<ul>{% for name, amount in rows %}<li>{{ name }}: {{ amount }}</li>{% endfor %}</ul>"
    "{{ footer }}"
)


def render_report(title, rows):
    environment = Environment(autoescape=True)
    footer = Markup("<footer>Generated by <b>ReportKit</b></footer>")
    return environment.from_string(TEMPLATE).render(title=title, rows=rows, footer=footer)


def total(rows):
    return sum(amount for _, amount in rows)
