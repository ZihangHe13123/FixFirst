from report.render import render_report, total


def test_title_is_escaped():
    assert "<h1>&lt;Q3&gt;</h1>" in render_report("<Q3>", [])


def test_footer_is_kept_as_html():
    assert "<footer>Generated by <b>ReportKit</b></footer>" in render_report("Q3", [])


def test_rows_are_listed():
    html = render_report("Q3", [("Ann", 3), ("Bo", 4)])
    assert "<li>Ann: 3</li>" in html and "<li>Bo: 4</li>" in html


def test_total():
    assert total([("Ann", 3), ("Bo", 4)]) == 7
